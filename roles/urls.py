# DefaultRouter automatically generates URL patterns
# for all CRUD operations of a ViewSet.
from rest_framework.routers import DefaultRouter

# Import the ViewSets that handle Role, Permission and Module APIs.
from .views import RoleViewSet, PermissionViewSet, ModuleViewSet


# Create a router to manage API URLs automatically.
router = DefaultRouter()

# Register RoleViewSet with the URL prefix 'roles'.
# Generates endpoints like GET /api/roles/ and POST /api/roles/.
router.register('roles', RoleViewSet)

# Register PermissionViewSet.
# Generates endpoints like GET /api/permissions/ and POST /api/permissions/.
router.register('permissions', PermissionViewSet)

# Register ModuleViewSet.
# Generates endpoints like GET /api/modules/ and POST /api/modules/.
router.register('modules', ModuleViewSet)

# Get all URL patterns generated by the router.
urlpatterns = router.urls